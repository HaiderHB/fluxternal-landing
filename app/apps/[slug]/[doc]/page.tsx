import type { Metadata } from 'next'
import Link from 'next/link'
import { notFound } from 'next/navigation'
import { PageShell } from '@/components/site/page-shell'
import { getDoc, listApps, longDate } from '@/lib/apps'

export const dynamicParams = false

export function generateStaticParams() {
  return listApps().flatMap((app) => app.pages.map((page) => ({ slug: app.slug, doc: page.slug })))
}

export async function generateMetadata({ params }: { params: Promise<{ slug: string; doc: string }> }): Promise<Metadata> {
  const { slug, doc } = await params
  const found = getDoc(slug, doc)
  if (!found) return {}
  return { title: `${found.page.title} — Fluxternal Inc.`, description: found.page.description }
}

export default async function LegalDocPage({ params }: { params: Promise<{ slug: string; doc: string }> }) {
  const { slug, doc } = await params
  const found = getDoc(slug, doc)
  if (!found) notFound()
  const { app, page, html } = found
  const dated = page.eyebrow === 'Legal'
  const siblings = app.pages.filter((p) => p.slug !== page.slug)

  return (
    <PageShell>
      <div className="mx-auto max-w-3xl px-6 py-20 md:py-28">
        <nav aria-label="Breadcrumb" className="flex flex-wrap items-center gap-2 text-sm text-foreground/50">
          <Link href="/apps" className="transition-colors hover:text-foreground">
            Apps
          </Link>
          <span aria-hidden="true">/</span>
          <Link href={`/apps/${app.slug}`} className="transition-colors hover:text-foreground">
            {app.name}
          </Link>
          <span aria-hidden="true">/</span>
          <span className="text-foreground/80">{page.heading}</span>
        </nav>

        <header className="mt-8">
          <p className="text-sm uppercase tracking-[0.2em] text-foreground/50">
            {page.eyebrow} · {app.name}
          </p>
          <h1 className="mt-4 font-display text-4xl font-normal leading-tight tracking-tight text-foreground text-balance md:text-5xl">
            {page.heading}
          </h1>
          {dated && (
            <p className="mt-4 text-sm text-foreground/50">
              Last updated {longDate(app.effectiveDate)} · Effective {longDate(app.effectiveDate)}
            </p>
          )}
        </header>

        {/* Generated by the app's launchkit from its data manifest; see content/apps/<slug>/ */}
        <article className="legal-doc mt-12" dangerouslySetInnerHTML={{ __html: html }} />

        <footer className="mt-16 border-t border-foreground/10 pt-8">
          <p className="text-xs uppercase tracking-[0.2em] text-foreground/50">Also for {app.name}</p>
          <ul className="mt-4 flex flex-wrap gap-x-6 gap-y-2">
            {siblings.map((p) => (
              <li key={p.slug}>
                <Link href={`/apps/${app.slug}/${p.slug}`} className="text-sm text-foreground/70 transition-colors hover:text-foreground">
                  {p.heading}
                </Link>
              </li>
            ))}
            <li>
              <a href={`mailto:${app.supportEmail}`} className="text-sm text-foreground/70 transition-colors hover:text-foreground">
                {app.supportEmail}
              </a>
            </li>
          </ul>
        </footer>
      </div>
    </PageShell>
  )
}
